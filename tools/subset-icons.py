# /// script
# requires-python = ">=3.11"
# dependencies = ["fonttools[woff]==4.66.1"]
# ///
"""Builds the bundled icon font from the Material Symbols Sharp variable font.

Reads the glyph names in src/ui/icon-names.json, subsets the font from the material-symbols
dev dependency to those glyphs, pins FILL 0, wght 400 and opsz 20, keeps GRAD from -25 to 0,
and writes src/assets/icons/material-symbols-sharp.woff2 and src/ui/icon-glyphs.ts.

Run it with `pnpm icons`. The output is byte-identical between runs.
"""

import hashlib
import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
NAMES_FILE = ROOT / "src/ui/icon-names.json"
PACKAGE_DIR = ROOT / "node_modules/material-symbols"
SOURCE_FONT = PACKAGE_DIR / "material-symbols-sharp.woff2"
OUTPUT_FONT = ROOT / "src/assets/icons/material-symbols-sharp.woff2"
OUTPUT_GLYPHS = ROOT / "src/ui/icon-glyphs.ts"
FORBIDDEN_WORDS = ("awesome", "magic", "sparkle")


def main() -> None:
    names = json.loads(NAMES_FILE.read_text(encoding="utf-8"))
    forbidden = [name for name in names if any(word in name for word in FORBIDDEN_WORDS)]
    if forbidden:
        sys.exit(f"Sparkle and magic glyphs are not bundled: {', '.join(forbidden)}")

    # recalcTimestamp=False keeps the source's head.modified, so reruns are byte-identical.
    font = TTFont(SOURCE_FONT, recalcTimestamp=False)
    codepoints = codepoints_by_name(font)
    missing = [name for name in names if name not in codepoints]
    if missing:
        sys.exit(f"Not in Material Symbols Sharp: {', '.join(missing)}")

    # Subset first: instancing the full font fails with KeyError: '.notdef'.
    options = subset.Options()
    options.layout_features = []
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[codepoints[name] for name in names])
    subsetter.subset(font)
    instancer.instantiateVariableFont(
        font, {"FILL": 0, "wght": 400, "opsz": 20, "GRAD": (-25, 0)}, inplace=True
    )

    font.flavor = "woff2"
    OUTPUT_FONT.parent.mkdir(parents=True, exist_ok=True)
    font.save(OUTPUT_FONT)

    version = json.loads((PACKAGE_DIR / "package.json").read_text(encoding="utf-8"))["version"]
    digest = hashlib.sha256(OUTPUT_FONT.read_bytes()).hexdigest()
    OUTPUT_GLYPHS.write_text(glyphs_module(names, codepoints, version, digest), encoding="utf-8")
    print(f"Wrote {len(names)} glyphs to {OUTPUT_FONT.relative_to(ROOT)} ({digest}).")


def codepoints_by_name(font: TTFont) -> dict[str, int]:
    """Maps each glyph name to its lowest codepoint; some glyphs have several."""
    codepoints: dict[str, int] = {}
    for codepoint, glyph_name in sorted(font.getBestCmap().items()):
        codepoints.setdefault(glyph_name, codepoint)
    return codepoints


def glyphs_module(names: list[str], codepoints: dict[str, int], version: str, digest: str) -> str:
    entries = "".join(f'  {name}: "\\u{{{codepoints[name]:x}}}",\n' for name in names)
    return (
        f"// Generated by tools/subset-icons.py from material-symbols {version}. Do not edit.\n"
        "// Run `pnpm icons` after changing src/ui/icon-names.json.\n"
        "\n"
        "export const glyphs = {\n"
        f"{entries}"
        "} as const;\n"
        "\n"
        "/** SHA-256 of src/assets/icons/material-symbols-sharp.woff2. */\n"
        f'export const fontSha256 = "{digest}";\n'
    )


if __name__ == "__main__":
    main()
